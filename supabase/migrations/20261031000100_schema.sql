create extension if not exists pgcrypto;

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  description text not null default '',
  price_cents integer not null default 0 check (price_cents >= 0),
  old_price_cents integer check (old_price_cents is null or old_price_cents >= 0),
  stock integer not null default 0 check (stock >= 0),
  category_id text not null,
  subcategory_id text,
  collection text check (collection is null or collection in ('combos', 'nuevos')),
  icon text not null default 'toolbox',
  status text not null default 'published' check (status in ('published', 'hidden')),
  deleted_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint products_code_not_blank check (length(btrim(code)) > 0),
  constraint products_name_not_blank check (length(btrim(name)) > 0)
);

create table if not exists public.product_images (
  id uuid primary key default gen_random_uuid(),
  product_id bigint not null references public.products(id) on delete cascade,
  storage_path text not null unique,
  alt text not null default '',
  sort_order integer not null default 0 check (sort_order >= 0),
  is_cover boolean not null default false,
  created_at timestamptz not null default now()
);

create unique index if not exists product_images_one_cover_idx
  on public.product_images (product_id)
  where is_cover;

create index if not exists product_images_product_id_idx
  on public.product_images (product_id, sort_order);

create index if not exists products_public_catalog_idx
  on public.products (category_id, subcategory_id)
  where deleted_at is null and status = 'published';

create index if not exists products_status_idx
  on public.products (status, deleted_at);

create table if not exists public.audit_log (
  id bigint generated by default as identity primary key,
  user_id uuid,
  action text not null,
  entity text not null,
  entity_id text,
  before jsonb,
  after jsonb,
  created_at timestamptz not null default now()
);

create index if not exists audit_log_created_at_idx
  on public.audit_log (created_at desc);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public, auth
as $$
  select coalesce((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin', false);
$$;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists products_set_updated_at on public.products;
create trigger products_set_updated_at
  before update on public.products
  for each row
  execute function public.set_updated_at();

create or replace function public.log_audit()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_action text;
  v_entity_id text;
  v_before jsonb;
  v_after jsonb;
begin
  if current_setting('ferromax.audit_skip', true) = 'on' then
    return null;
  end if;

  if tg_op = 'DELETE' then
    v_before := to_jsonb(old);
    v_after := null;
    v_entity_id := old.id::text;
  elsif tg_op = 'INSERT' then
    v_before := null;
    v_after := to_jsonb(new);
    v_entity_id := new.id::text;
  else
    v_before := to_jsonb(old);
    v_after := to_jsonb(new);
    v_entity_id := new.id::text;
  end if;

  if tg_table_name = 'products' then
    if tg_op = 'INSERT' then
      v_action := 'INSERT';
    elsif tg_op = 'DELETE' then
      v_action := 'DELETE';
    elsif old.deleted_at is null and new.deleted_at is not null then
      v_action := 'SOFT_DELETE';
    elsif old.deleted_at is not null and new.deleted_at is null then
      v_action := 'RESTORE';
    else
      v_action := 'UPDATE';
    end if;
  else
    if tg_op = 'INSERT' then
      v_action := 'IMAGES_UPLOAD';
    elsif tg_op = 'DELETE' then
      v_action := 'IMAGE_DELETE';
    else
      v_action := 'IMAGE_UPDATE';
    end if;
  end if;

  insert into public.audit_log (user_id, action, entity, entity_id, before, after)
  values (auth.uid(), v_action, tg_table_name, v_entity_id, v_before, v_after);

  return null;
end;
$$;

drop trigger if exists products_audit on public.products;
create trigger products_audit
  after insert or update or delete on public.products
  for each row
  execute function public.log_audit();

drop trigger if exists product_images_audit on public.product_images;
create trigger product_images_audit
  after insert or update or delete on public.product_images
  for each row
  execute function public.log_audit();

-- Permisos de tabla. RLS sigue siendo la barrera real.
grant usage on schema public to anon, authenticated;
grant select on public.products, public.product_images to anon, authenticated;
grant insert, update, delete on public.products, public.product_images to authenticated;
grant select on public.audit_log to authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;
grant execute on function public.is_admin() to anon, authenticated, service_role;
